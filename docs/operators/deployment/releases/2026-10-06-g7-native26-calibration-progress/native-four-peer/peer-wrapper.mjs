import {writeFileSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const out=process.argv[2];
const args=[join(out,'peer-reader.mjs'),out];
const at=new Date().toISOString();
const r=spawnSync(process.execPath,args,{cwd:'C:/cinagroup/cinatoken',encoding:null,maxBuffer:20*1024*1024,windowsHide:true});
const finishedAt=new Date().toISOString();
const info=b=>({bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')});
const stdout=r.stdout??Buffer.alloc(0),stderr=r.stderr??Buffer.alloc(0);
writeFileSync(join(out,'peer-review.stdout.log'),stdout,{flag:'wx'});
writeFileSync(join(out,'peer-review.stderr.log'),stderr,{flag:'wx'});
const receipt={schema:'cinatoken.native-four-independent-peer.closed.v1',at,finishedAt,executable:process.execPath,args,cwd:'C:/cinagroup/cinatoken',actualExit:r.status,signal:r.signal??null,spawnError:r.error?String(r.error):null,stdout:join(out,'peer-review.stdout.log'),stderr:join(out,'peer-review.stderr.log'),stdoutInfo:info(stdout),stderrInfo:info(stderr)};
writeFileSync(join(out,'peer-review.closed.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
process.stdout.write(JSON.stringify(receipt)+'\n');
process.stdout.write(stdout);process.stderr.write(stderr);
process.exitCode=r.status??1;
