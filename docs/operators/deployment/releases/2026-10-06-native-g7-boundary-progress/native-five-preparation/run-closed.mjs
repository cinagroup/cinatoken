import { spawn } from 'node:child_process';
import { open, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const out = dirname(fileURLToPath(import.meta.url));
const [label, executable, ...args] = process.argv.slice(2);
if (!/^[a-z0-9-]+$/.test(label)) throw Error('Invalid evidence label');
const stdoutPath = join(out,label+'.stdout.log'), stderrPath = join(out,label+'.stderr.log');
const stdout = await open(stdoutPath,'wx'), stderr = await open(stderrPath,'wx');
const at = new Date().toISOString();
const child = spawn(executable,args,{cwd:'C:/cinagroup/cinatoken',windowsHide:true,stdio:['ignore',stdout.fd,stderr.fd]});
const result = await new Promise(resolve => { child.once('error',error => resolve({actualExit:null,signal:null,spawnError:String(error)})); child.once('close',(actualExit,signal)=>resolve({actualExit,signal})); });
await stdout.close(); await stderr.close();
const receipt = {at,finishedAt:new Date().toISOString(),executable,args,cwd:'C:/cinagroup/cinatoken',...result,stdout:stdoutPath,stderr:stderrPath};
await writeFile(join(out,label+'.closed.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
process.stdout.write(JSON.stringify(receipt)+'\n');
process.exitCode = Number.isInteger(result.actualExit) ? result.actualExit : 1;
