import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { verifyRelease } from 'file:///C:/cinagroup/cinatoken/packages/web/scripts/package-release.mjs';
import { createWebWranglerConfig } from 'file:///C:/cinagroup/cinatoken/packages/web/scripts/gen-web-wrangler.mjs';
const [id, mode, label] = process.argv.slice(2);
assert.match(id ?? '', /^[a-zA-Z0-9._-]+$/);
assert.ok(['public', 'all'].includes(mode));
assert.match(label ?? '', /^[a-z0-9-]+$/);
const temp = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const root = 'C:/cinagroup/cinatoken';
const release = verifyRelease(root, id);
assert.ok(release.server, 'Verified server artifact required');
const config = createWebWranglerConfig({ WEB_WORKER_NAME: 'cinatoken-web', ADMIN_WORKER_NAME: 'cinatoken-admin', CINATOKEN_WEB_PUBLIC_ENABLED: 'true', CINATOKEN_WEB_PUBLIC_ORIGIN: 'https://cinatoken.com', CINATOKEN_WEB_PROXY_ORIGINS: 'https://api.cinatoken.com' }, release.assets, path.join(release.server, 'worker/index.mjs'));
if (mode === 'all') for (const key of Object.keys(config.vars)) if (key.endsWith('_ENABLED')) config.vars[key] = 'true';
assert.equal(Object.keys(config.vars).filter(k => k.endsWith('_ENABLED')).length, 29);
config.account_id = '7ea8e46d8210bad342fa7595f7935fea';
config.workers_dev = false;
config.preview_urls = false;
config.routes = [];
delete config.$schema;
const target = path.join(temp, label + '.wrangler.json');
fs.writeFileSync(target, JSON.stringify(config, null, 2) + '\n', { flag: 'wx' });
const proof = { at: new Date().toISOString(), actualExit: 0, releaseId: id, manifestSha256: release.manifestSha256, assetFiles: release.manifest.files.length, serverFiles: release.manifest.serverFiles?.length, buildContract: release.manifest.buildContract, enabledFlags: Object.entries(config.vars).filter(([k, v]) => k.endsWith('_ENABLED') && v === 'true').map(([k]) => k), configPath: target, routes: [], workersDev: false, previewUrls: false, services: config.services, productionRouteChanged: false };
fs.writeFileSync(path.join(temp, label + '.config-proof.json'), JSON.stringify(proof, null, 2) + '\n', { flag: 'wx' });
console.log(JSON.stringify(proof));
