import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
const directory=path.dirname(fileURLToPath(import.meta.url));
const [name,key,...args]=process.argv.slice(2);
if(!/^[a-z0-9-]+$/.test(name??''))throw new Error('Invalid record name');
const commands={git:['C:/Program Files/Git/cmd/git.exe'],gh:['C:/Program Files/GitHub CLI/gh.exe'],node:['C:/Program Files/nodejs/node.exe'],npm:['C:/Program Files/nodejs/node.exe','C:/Program Files/nodejs/node_modules/npm/bin/npm-cli.js']};
if(!commands[key])throw new Error('Unknown executable');
const stdout=path.join(directory,name+'.stdout.log'),stderr=path.join(directory,name+'.stderr.log'),resultPath=path.join(directory,name+'.result.json');
const out=fs.openSync(stdout,'wx'),err=fs.openSync(stderr,'wx'),at=new Date().toISOString();
const [executable,...prefix]=commands[key];
const child=spawn(executable,[...prefix,...args],{cwd:'C:/cinagroup/cinatoken',windowsHide:true,env:{...process.env,WRANGLER_LOG_PATH:path.join(directory,name+'.wrangler.log'),WRANGLER_SEND_METRICS:'false'},stdio:['ignore',out,err]});
let spawnError;child.once('error',e=>{spawnError=e.code??'spawn_error';});
const result=await new Promise(resolve=>child.once('close',(code,signal)=>resolve({actualExit:code,signal})));
fs.closeSync(out);fs.closeSync(err);
const describe=p=>{const b=fs.readFileSync(p);return {path:p,bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')};};
const record={at,finishedAt:new Date().toISOString(),executable,args:[...prefix,...args],cwd:'C:/cinagroup/cinatoken',...result,...(spawnError?{spawnError}:{}),stdout:describe(stdout),stderr:describe(stderr)};
fs.writeFileSync(resultPath,JSON.stringify(record,null,2)+'\n',{flag:'wx'});
const tail=p=>fs.readFileSync(p,'utf8').split(/\r?\n/).slice(-8).map(s=>s.length>800?s.slice(0,800)+' [display truncated; raw file complete]':s);
console.log(JSON.stringify({...record,resultPath,stdoutLastLines:tail(stdout),stderrLastLines:tail(stderr)}));
process.exitCode=result.actualExit??1;
