import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawn} from 'node:child_process';
const own=path.dirname(fileURLToPath(import.meta.url));
const [label,key,...args]=process.argv.slice(2);
if(!/^[a-z0-9-]{1,64}$/.test(label??''))throw new Error('Use fresh owned label');
const commands={node:['C:/Program Files/nodejs/node.exe'],npm:['C:/Program Files/nodejs/node.exe','C:/Program Files/nodejs/node_modules/npm/bin/npm-cli.js'],git:['C:/Program Files/Git/cmd/git.exe'],gh:['C:/Program Files/GitHub CLI/gh.exe'],python:['C:/Users/cina/.cache/codex-runtimes/codex-primary-runtime/dependencies/python/python.exe']};
if(!commands[key])throw new Error('Unknown command');
const [exe,...prefix]=commands[key];
const stdout=path.join(own,label+'.stdout.log'),stderr=path.join(own,label+'.stderr.log');
const fds=[fs.openSync(stdout,'wx'),fs.openSync(stderr,'wx')];
const startedAt=new Date().toISOString();
const child=spawn(exe,[...prefix,...args],{cwd:'C:/cinagroup/cinatoken',windowsHide:true,env:{...process.env,TSX_TSCONFIG_PATH:'C:/cinagroup/cinatoken/packages/web/tsconfig.test.json',WRANGLER_LOG_PATH:path.join(own,label+'.wrangler.log'),WRANGLER_SEND_METRICS:'false'},stdio:['ignore',...fds]});
let spawnError=null;child.once('error',e=>{spawnError=e.code??e.message;});
const close=await new Promise(resolve=>child.once('close',(actualExitCode,signal)=>resolve({actualExitCode,signal})));
fds.forEach(fd=>fs.closeSync(fd));
const describe=p=>{const b=fs.readFileSync(p);return{path:p,bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')}};
const record={startedAt,closedAt:new Date().toISOString(),executable:exe,args:[...prefix,...args],cwd:'C:/cinagroup/cinatoken',...close,spawnError,stdout:describe(stdout),stderr:describe(stderr)};
const result=path.join(own,label+'.result.json');
fs.writeFileSync(result,JSON.stringify(record,null,2)+'\n',{flag:'wx'});
const tail=p=>fs.readFileSync(p,'utf8').split(/\r?\n/).slice(-6).map(x=>x.length>1200?x.slice(0,1200)+' [display only truncated; raw original complete]':x);
console.log(JSON.stringify({...record,resultPath:result,stdoutTail:tail(stdout),stderrTail:tail(stderr)}));
process.exitCode=close.actualExitCode??1;
