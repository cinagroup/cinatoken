/** Keep Wrangler's exact binding fields while preventing Worker-only globals
 * (especially required NodeJS.ProcessEnv fields) from leaking into Node tools. */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const contracts = [
  ['complete-text-no-fetch-recovery-v389-env.d.ts', 'CompleteTextNoFetchRecoveryV389Env', 'COMPLETE_TEXT_NO_FETCH_RECOVERY_ENABLED'],
  ['complete-text-holder-v390-env.d.ts', 'CompleteTextHolderV390Env', 'COMPLETE_TEXT_HOLDER_ENABLED'],
  ['complete-text-response-holder-v394-env.d.ts', 'CompleteTextResponseHolderV394Env', 'COMPLETE_TEXT_HOLDER_ENABLED'],
];

assert.ok(process.argv.length === 2 || (process.argv.length === 3 && process.argv[2] === '--check'));
for (const [filename, interfaceName, bindingName] of contracts) {
  const path = new URL(`../src/runtime/${filename}`, import.meta.url);
  const source = readFileSync(path, 'utf8');
  assert.match(source, /Generated by Wrangler/);
  assert.ok(source.includes(`interface ${interfaceName} extends __BaseEnv_${interfaceName}`));
  assert.ok(source.includes(`\t${bindingName}: string;`));
  const suffix = `\n// Scope this Worker-only binding contract to its module, including Wrangler's\n` +
    `// NodeJS.ProcessEnv projection; it must not alter unrelated Node scripts.\n` +
    `import type { Hyperdrive } from '@cloudflare/workers-types';\n` +
    `export type { ${interfaceName} };\n`;
  if (process.argv[2] === '--check') {
    assert.ok(source.endsWith(suffix), `Regenerate and isolate ${filename}`);
  } else if (!source.endsWith(suffix)) {
    assert.ok(!source.includes("// Scope this Worker-only binding contract to its module"),
      `Unexpected existing isolation suffix in ${filename}`);
    writeFileSync(path, source + suffix);
  }
}
console.log('COMPLETE_TEXT_WORKER_ENV_TYPES_ISOLATED');
