/** Mechanical module boundary for Wrangler output; never authors binding fields. */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const path = new URL('../../packages/proxy/scripts/staging/usage-recovery-control-env.d.ts', import.meta.url);
const suffix = '\n// Module scope prevents this Worker from merging Env/GlobalProps with the receiver.\nexport type { UsageRecoveryControlEnv };\n';
assert.ok(process.argv.length === 2 || (process.argv.length === 3 && process.argv[2] === '--check'));
const source = readFileSync(path, 'utf8');
assert.match(source, /Generated by Wrangler/);
assert.match(source, /USAGE_RECOVERY: Service<typeof import\("\.\/usage-recovery-worker"\).UsageRecovery>;/);
assert.match(source, /interface UsageRecoveryControlEnv extends __BaseEnv_UsageRecoveryControlEnv/);
if (process.argv[2] === '--check') assert.ok(source.endsWith(suffix), 'Regenerate and isolate control binding types');
else if (!source.endsWith(suffix)) writeFileSync(path, source + suffix);
console.log('RECOVERY_CONTROL_TYPES_MODULE_SCOPED');
